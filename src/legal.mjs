// Тексты политики обработки персональных данных и согласия на cookie (152-ФЗ).
// Сайт сам ничего не собирает: нет форм и регистрации. Персональными данными по позиции Роскомнадзора
// считаются только cookie и IP-адрес, которые получает Яндекс Метрика, поэтому политика описывает именно их.
// Реквизиты оператора задаются в SITE.operator в scripts/build.mjs.

const who = (site) => {
  const o = site.operator;
  const name = o.name ? `${o.name}${o.inn ? `, ИНН ${o.inn}` : ''}` : `владелец сайта ${site.domain}`;
  return { name, email: o.email };
};

